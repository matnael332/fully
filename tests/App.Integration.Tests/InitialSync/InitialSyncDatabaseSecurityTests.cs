namespace WorkContinuity.Integration.Tests.InitialSync;

/// <summary>
/// Gate 3F's persistence on databases created for the test, bootstrapped and then migrated from zero in the order the
/// rollout uses: the runtime role holds exactly read, insert and the column updates initial sync needs on each new table,
/// with row-level security enabled and forced and every delete refused; a source scope can never move to another
/// connection or resource and a sync row never advances its replay floor; a sync row's shape and scope-set versions are
/// checked by the database itself, so no Live row can stand on an earlier scope set; the ingress sequence is generated by
/// the database once, never supplied, never changed and never cached per session; a rerun of the global bootstrap
/// re-grants DELETE, which the restrictive policies still refuse and the recorded re-assertion removes; and the isolation
/// checks are not vacuous.
/// </summary>
/// <remarks>
/// The shared test database cannot give this evidence: the suite reruns the global bootstrap there. Each test creates its
/// own database by an exact name, drops it first in case a stopped run left it behind, and drops it at the end.
/// </remarks>
[Collection(DatabaseCollection.Name)]
public sealed class InitialSyncDatabaseSecurityTests(DatabaseFixture fixture)
{
    /// <summary>The re-assertion the Azure rollout runs in the same approved step as any bootstrap rerun (R3B-2).</summary>
    internal const string ReassertPrivilegesSql = """
        REVOKE ALL PRIVILEGES ON connector_source_scopes FROM workcontinuity_app;
        GRANT SELECT, INSERT ON connector_source_scopes TO workcontinuity_app;
        GRANT UPDATE (enabled, baseline_generation, updated_at_utc) ON connector_source_scopes TO workcontinuity_app;
        REVOKE ALL PRIVILEGES ON connection_syncs FROM workcontinuity_app;
        GRANT SELECT, INSERT ON connection_syncs TO workcontinuity_app;
        GRANT UPDATE (generation, state, provider_subject, authorized_at_utc, scope_version, generation_scope_version,
            buffer_start_fence, replay_fence, cutover_fence, claim_id, claimed_until_utc, attempts, next_attempt_at_utc,
            last_outcome, started_at_utc, live_at_utc, updated_at_utc)
            ON connection_syncs TO workcontinuity_app;
        REVOKE ALL PRIVILEGES ON connection_sync_scopes FROM workcontinuity_app;
        GRANT SELECT, INSERT ON connection_sync_scopes TO workcontinuity_app;
        GRANT UPDATE (state, attempts, last_outcome, pages_read, objects_read, fields_applied, completed_at_utc)
            ON connection_sync_scopes TO workcontinuity_app;
        REVOKE ALL PRIVILEGES ON active_snapshot_objects, active_snapshot_fields FROM workcontinuity_app;
        GRANT SELECT ON active_snapshot_objects, active_snapshot_fields TO workcontinuity_app;
        """;

    private static readonly string[] Views = ["active_snapshot_objects", "active_snapshot_fields"];

    private static readonly string[] Tables = ["connector_source_scopes", "connection_syncs", "connection_sync_scopes"];

    private static readonly Dictionary<string, string> UpdatableColumns = new(StringComparer.Ordinal)
    {
        ["connector_source_scopes"] = "baseline_generation,enabled,updated_at_utc",
        ["connection_syncs"] = "attempts,authorized_at_utc,buffer_start_fence,claim_id,claimed_until_utc,cutover_fence,generation,"
            + "generation_scope_version,last_outcome,live_at_utc,next_attempt_at_utc,provider_subject,replay_fence,scope_version,"
            + "started_at_utc,state,updated_at_utc",
        ["connection_sync_scopes"] = "attempts,completed_at_utc,fields_applied,last_outcome,objects_read,pages_read,state",
    };

    private CancellationToken Token => TestContext.Current.CancellationToken;

    [Fact]
    public async Task After_bootstrap_then_migration_the_runtime_role_holds_exactly_what_initial_sync_needs_under_forced_row_level_security()
    {
        await using var fresh = await FreshDatabase.CreateAsync(fixture, "wce_it_gate3f_privileges", Token);
        await fresh.BootstrapAsync(Token);
        await fresh.MigrateAsync(Token);

        foreach (var table in Tables)
        {
            Assert.Equal("INSERT,SELECT", await fresh.ScalarAsync(TablePrivileges(table), Token));
            Assert.Equal(UpdatableColumns[table], await fresh.ScalarAsync(UpdateColumns(table), Token));
            Assert.Equal("true:true", await fresh.ScalarAsync($"SELECT relrowsecurity || ':' || relforcerowsecurity FROM pg_class WHERE relname = '{table}';", Token));
            Assert.Equal(
                $"no_delete_{table}:RESTRICTIVE:DELETE,tenant_isolation_{table}:PERMISSIVE:ALL",
                await fresh.ScalarAsync($"SELECT string_agg(policyname || ':' || permissive || ':' || cmd, ',' ORDER BY policyname) FROM pg_policies WHERE tablename = '{table}';", Token));
        }

        // The current work view: run as the caller, and read-only to the runtime role.
        foreach (var view in Views)
        {
            Assert.Equal("SELECT", await fresh.ScalarAsync(TablePrivileges(view), Token));
            Assert.Equal("security_invoker=true", await fresh.ScalarAsync($"SELECT array_to_string(reloptions, ',') FROM pg_class WHERE relname = '{view}' AND relkind = 'v';", Token));
        }

        // The intended path works as the runtime role.
        var (tenant, connection) = await fresh.SeedConnectionAsync(Token);
        Assert.Equal(1L, await fresh.RuntimeAsync(tenant, InsertScope(tenant, connection, "9001"), Token, commit: true));
        Assert.Equal(1L, await fresh.RuntimeAsync(tenant, InsertSync(tenant, connection), Token, commit: true));
        Assert.Equal(1L, await fresh.RuntimeAsync(tenant, InsertSyncScope(tenant, connection, "9001"), Token, commit: true));
        Assert.Equal(1L, await fresh.RuntimeAsync(tenant, "UPDATE connector_source_scopes SET enabled = false, updated_at_utc = now();", Token));
        Assert.Equal(1L, await fresh.RuntimeAsync(tenant, "UPDATE connection_syncs SET state = 'Reading', generation = generation + 1, buffer_start_fence = 7;", Token));
        Assert.Equal(1L, await fresh.RuntimeAsync(tenant, "UPDATE connection_sync_scopes SET state = 'Completed', pages_read = 1, completed_at_utc = now();", Token));

        // A scope never moves to another connection or resource, a sync row never changes its identity or advances its
        // replay floor, and a generation's scope stays the generation's: refused by privilege.
        foreach (var sql in new[]
                 {
                     $"UPDATE connector_source_scopes SET connection_id = '{Guid.NewGuid():D}';",
                     "UPDATE connector_source_scopes SET resource_id = '9002';",
                     "UPDATE connector_source_scopes SET source_system = 'synthetic';",
                     $"UPDATE connector_source_scopes SET tenant_id = '{Guid.NewGuid():D}';",
                     "UPDATE connection_syncs SET replay_floor = replay_floor + 1;",
                     "UPDATE connection_syncs SET source_system = 'synthetic';",
                     $"UPDATE connection_syncs SET connection_id = '{Guid.NewGuid():D}';",
                     "UPDATE connection_sync_scopes SET resource_id = '9002';",
                     "UPDATE connection_sync_scopes SET generation = generation + 1;",
                 })
        {
            var refused = await Assert.ThrowsAsync<PostgresException>(() => fresh.RuntimeAsync(tenant, sql, Token));
            Assert.True(PostgresErrorCodes.InsufficientPrivilege == refused.SqlState, sql);
        }

        foreach (var table in Tables)
        {
            foreach (var sql in new[] { $"DELETE FROM {table};", $"TRUNCATE {table};" })
            {
                var refused = await Assert.ThrowsAsync<PostgresException>(() => fresh.RuntimeAsync(tenant, sql, Token));
                Assert.True(PostgresErrorCodes.InsufficientPrivilege == refused.SqlState, sql);
            }
        }
    }

    [Fact]
    public async Task A_sync_rows_shape_and_scope_set_versions_are_checked_by_the_database_so_no_live_row_stands_on_an_earlier_scope_set()
    {
        await using var fresh = await FreshDatabase.CreateAsync(fixture, "wce_it_gate3f_versions", Token);
        await fresh.BootstrapAsync(Token);
        await fresh.MigrateAsync(Token);
        var (tenant, connection) = await fresh.SeedConnectionAsync(Token);
        var (other, otherConnection) = await fresh.SeedConnectionAsync(Token);

        // NotStarted: no generation, authority, start or generation scope set; anything else has all four.
        Assert.Equal(1L, await fresh.RuntimeAsync(tenant, InsertNotStarted(tenant, connection), Token, commit: true));
        foreach (var (sql, constraint) in new[]
                 {
                     ("UPDATE connection_syncs SET provider_subject = '58201774';", "ck_connection_syncs_not_started"),
                     ("UPDATE connection_syncs SET generation_scope_version = 1;", "ck_connection_syncs_not_started"),
                     ("UPDATE connection_syncs SET generation = 1;", "ck_connection_syncs_generation"),
                     ("UPDATE connection_syncs SET state = 'Buffering', generation = 1;", "ck_connection_syncs_not_started"),
                 })
        {
            var refused = await Assert.ThrowsAsync<PostgresException>(() => fresh.RuntimeAsync(tenant, sql, Token));
            Assert.True((PostgresErrorCodes.CheckViolation, constraint) == (refused.SqlState, refused.ConstraintName), sql);
        }

        // Its first generation reads the scope set as it stands, and only that version may be Live.
        Assert.Equal(1L, await fresh.RuntimeAsync(
            tenant,
            "UPDATE connection_syncs SET generation = 1, state = 'Buffering', provider_subject = '58201774', authorized_at_utc = now(), started_at_utc = now(), generation_scope_version = scope_version;",
            Token,
            commit: true));
        Assert.Equal(1L, await fresh.RuntimeAsync(tenant, "UPDATE connection_syncs SET state = 'Live', cutover_fence = 5, live_at_utc = now();", Token, commit: true));

        // A scope-set change that leaves Live in place, a stale generation becoming Live, and a generation ahead of the
        // scope set are each refused by the database itself.
        foreach (var sql in new[]
                 {
                     "UPDATE connection_syncs SET scope_version = scope_version + 1;",
                     "UPDATE connection_syncs SET generation_scope_version = scope_version + 1;",
                     "UPDATE connection_syncs SET scope_version = 0, generation_scope_version = 0;",
                 })
        {
            var refused = await Assert.ThrowsAsync<PostgresException>(() => fresh.RuntimeAsync(tenant, sql, Token));
            Assert.True((PostgresErrorCodes.CheckViolation, "ck_connection_syncs_scope_version") == (refused.SqlState, refused.ConstraintName), sql);
        }

        Assert.Equal(1L, await fresh.RuntimeAsync(
            tenant,
            "UPDATE connection_syncs SET scope_version = scope_version + 1, state = 'RequiresRestart', cutover_fence = NULL, live_at_utc = NULL;",
            Token,
            commit: true));
        var stale = await Assert.ThrowsAsync<PostgresException>(() => fresh.RuntimeAsync(tenant, "UPDATE connection_syncs SET state = 'Live', cutover_fence = 5, live_at_utc = now();", Token));
        Assert.Equal((PostgresErrorCodes.CheckViolation, "ck_connection_syncs_scope_version"), (stale.SqlState, stale.ConstraintName));
        Assert.Equal("RequiresRestart:2:1", await fresh.ScalarAsync(
            $"SELECT state || ':' || scope_version || ':' || generation_scope_version FROM connection_syncs WHERE connection_id = '{connection:D}';", Token));

        // Another tenant's row is neither seen nor changed by this tenant's statements.
        Assert.Equal(1L, await fresh.RuntimeAsync(other, InsertNotStarted(other, otherConnection), Token, commit: true));
        Assert.Equal(0L, await fresh.RuntimeAsync(tenant, $"UPDATE connection_syncs SET scope_version = scope_version + 1 WHERE connection_id = '{otherConnection:D}';", Token, commit: true));
        Assert.Equal("NotStarted:1", await fresh.ScalarAsync(
            $"SELECT state || ':' || scope_version FROM connection_syncs WHERE connection_id = '{otherConnection:D}';", Token));
    }

    [Fact]
    public async Task The_ingress_sequence_is_generated_once_never_supplied_never_changed_and_never_cached_per_session()
    {
        await using var fresh = await FreshDatabase.CreateAsync(fixture, "wce_it_gate3f_sequence", Token);
        await fresh.BootstrapAsync(Token);
        await fresh.MigrateAsync(Token);
        var (tenant, connection) = await fresh.SeedConnectionAsync(Token);

        // Generated by the database at insert, in insert order across sessions: one value at a time, never cached.
        Assert.Equal("a:1:1", await fresh.ScalarAsync(
            """
            SELECT a.attidentity::text || ':' || s.seqcache || ':' || s.seqincrement
            FROM pg_attribute a
            JOIN pg_sequence s ON s.seqrelid = pg_get_serial_sequence('public.raw_receipts', 'ingress_sequence')::regclass
            WHERE a.attrelid = 'public.raw_receipts'::regclass AND a.attname = 'ingress_sequence';
            """,
            Token));
        Assert.Equal(1L, await fresh.RuntimeAsync(tenant, InsertReceipt(tenant, connection, supplied: null), Token, commit: true));
        Assert.Equal(1L, await fresh.RuntimeAsync(tenant, InsertReceipt(tenant, connection, supplied: null), Token, commit: true));
        Assert.Equal("1,2", await fresh.ScalarAsync("SELECT string_agg(ingress_sequence::text, ',' ORDER BY ingress_sequence) FROM raw_receipts;", Token));

        // Never supplied by the application.
        var supplied = await Assert.ThrowsAsync<PostgresException>(() => fresh.RuntimeAsync(tenant, InsertReceipt(tenant, connection, supplied: 99), Token));
        Assert.Equal("428C9", supplied.SqlState); // generated_always: a value is never supplied for an identity always column

        // Never changed, not even by the schema owner: the identity refuses any value but a new one of its own, and the
        // trigger refuses that too.
        var explicitValue = await Assert.ThrowsAsync<PostgresException>(() => fresh.AdministrativeAsync("UPDATE raw_receipts SET ingress_sequence = ingress_sequence + 100;", Token));
        Assert.Equal("428C9", explicitValue.SqlState);
        var newValue = await Assert.ThrowsAsync<PostgresException>(() => fresh.AdministrativeAsync("UPDATE raw_receipts SET ingress_sequence = DEFAULT;", Token));
        Assert.Equal((PostgresErrorCodes.CheckViolation, "keep_ingress_sequence_raw_receipts"), (newValue.SqlState, newValue.ConstraintName));
        Assert.Equal("1,2", await fresh.ScalarAsync("SELECT string_agg(ingress_sequence::text, ',' ORDER BY ingress_sequence) FROM raw_receipts;", Token));

        // The trigger's function: no definer rights, a fixed search path, and no one may call it directly.
        Assert.Equal("false:search_path=pg_catalog, pg_temp:false", await fresh.ScalarAsync(
            """
            SELECT p.prosecdef || ':' || array_to_string(p.proconfig, ';') || ':'
                   || has_function_privilege('workcontinuity_app', p.oid, 'EXECUTE')
            FROM pg_proc p WHERE p.proname = 'keep_ingress_sequence';
            """,
            Token));
    }

    [Fact]
    public async Task A_bootstrap_rerun_re_grants_delete_which_the_restrictive_policies_still_refuse_until_the_reassertion_restores_the_exact_grants()
    {
        await using var fresh = await FreshDatabase.CreateAsync(fixture, "wce_it_gate3f_rerun", Token);
        await fresh.BootstrapAsync(Token);
        await fresh.MigrateAsync(Token);
        var (tenant, connection) = await fresh.SeedConnectionAsync(Token);
        await fresh.RuntimeAsync(tenant, InsertScope(tenant, connection, "9001"), Token, commit: true);
        await fresh.RuntimeAsync(tenant, InsertSync(tenant, connection), Token, commit: true);
        await fresh.RuntimeAsync(tenant, InsertSyncScope(tenant, connection, "9001"), Token, commit: true);

        // The hazard R3B-2 records for the Azure rollout: the unchanged bootstrap, rerun, re-grants DELETE and every column.
        await fresh.BootstrapAsync(Token);
        foreach (var table in Tables)
        {
            Assert.Equal("DELETE,INSERT,SELECT,UPDATE", await fresh.ScalarAsync(TablePrivileges(table), Token));

            // The restrictive policy keeps every row regardless: a delete finds nothing it may remove.
            Assert.Equal(0L, await fresh.RuntimeAsync(tenant, $"DELETE FROM {table};", Token));
            Assert.Equal(1L, await fresh.RuntimeAsync(tenant, $"SELECT count(*) FROM {table};", Token));
        }

        // The recorded re-assertion restores exactly read, insert and the column updates, and reading only of the views.
        await fresh.AdministrativeAsync(ReassertPrivilegesSql, Token);
        foreach (var table in Tables)
        {
            Assert.Equal("INSERT,SELECT", await fresh.ScalarAsync(TablePrivileges(table), Token));
            Assert.Equal(UpdatableColumns[table], await fresh.ScalarAsync(UpdateColumns(table), Token));
        }

        foreach (var view in Views)
        {
            Assert.Equal("SELECT", await fresh.ScalarAsync(TablePrivileges(view), Token));
        }
    }

    [Fact]
    public async Task The_current_work_view_shows_only_enabled_baselined_scopes_to_the_callers_own_tenant_and_the_check_is_not_vacuous()
    {
        await using var fresh = await FreshDatabase.CreateAsync(fixture, "wce_it_gate3f_view", Token);
        await fresh.BootstrapAsync(Token);
        await fresh.MigrateAsync(Token);
        var (tenant, taking) = await fresh.SeedConnectionAsync(Token);
        var (other, othersTaking) = await fresh.SeedConnectionAsync(Token);
        var never = Guid.CreateVersion7();
        await fresh.AdministrativeAsync(
            $"INSERT INTO connections (connection_id, tenant_id, source_system, status, created_at_utc) VALUES ('{never:D}', '{tenant.Value:D}', 'monday', 'Active', now());",
            Token);

        // One connection of the tenant takes part, with scope A current, B enabled but never read, and D disabled; another
        // never took part; and the other tenant's connection takes part with its own scope A current.
        await fresh.AdministrativeAsync(
            Seed(tenant, taking, participates: true, ("1", "A", null), ("2", "A", 2L), ("3", "B", null), ("4", "D", null), ("5", "X", null), ("6", null, null), ("7", "", null))
            + Seed(tenant, never, participates: false, ("8", null, null))
            + Seed(other, othersTaking, participates: true, ("1", "A", null))
            + $"""
              INSERT INTO connector_source_scopes (tenant_id, connection_id, source_system, resource_id, enabled, baseline_generation, created_at_utc, updated_at_utc)
              VALUES ('{tenant.Value:D}', '{taking:D}', 'monday', 'A', true, 1, now(), now()),
                     ('{tenant.Value:D}', '{taking:D}', 'monday', 'B', true, NULL, now(), now()),
                     ('{tenant.Value:D}', '{taking:D}', 'monday', 'D', false, NULL, now(), now()),
                     ('{other.Value:D}', '{othersTaking:D}', 'monday', 'A', true, 1, now(), now());
              """,
            Token);

        // Only the field of the current scope, with no baseline awaited, and the field of the connection that never took part.
        Assert.Equal([$"{taking:D}/1", $"{never:D}/8"], await fresh.RuntimeListAsync(tenant, Fields, Token));
        Assert.Equal([$"{taking:D}/1", $"{never:D}/8"], await fresh.RuntimeListAsync(tenant, Objects, Token));
        Assert.Equal([$"{othersTaking:D}/1"], await fresh.RuntimeListAsync(other, Fields, Token));
        Assert.Equal([$"{othersTaking:D}/1"], await fresh.RuntimeListAsync(other, Objects, Token));

        // Vacuity: the same view run as its owner instead of its caller would show the tenant the other tenant's state.
        foreach (var view in Views)
        {
            await fresh.AdministrativeAsync($"ALTER VIEW {view} SET (security_invoker = false);", Token);
        }

        Assert.Contains($"{othersTaking:D}/1", await fresh.RuntimeListAsync(tenant, Fields, Token));
        Assert.Contains($"{othersTaking:D}/1", await fresh.RuntimeListAsync(tenant, Objects, Token));
    }

    [Fact]
    public async Task A_disabled_scope_can_hold_no_baseline_and_a_field_awaits_one_only_at_a_real_version()
    {
        await using var fresh = await FreshDatabase.CreateAsync(fixture, "wce_it_gate3f_baseline", Token);
        await fresh.BootstrapAsync(Token);
        await fresh.MigrateAsync(Token);
        var (tenant, connection) = await fresh.SeedConnectionAsync(Token);
        Assert.Equal(1L, await fresh.RuntimeAsync(tenant, InsertScope(tenant, connection, "9001"), Token, commit: true));
        Assert.Equal(1L, await fresh.RuntimeAsync(tenant, InsertTarget(tenant, connection, "9001"), Token, commit: true));

        // An enabled scope takes a baseline; disabling it must drop the baseline in the same statement.
        Assert.Equal(1L, await fresh.RuntimeAsync(tenant, "UPDATE connector_source_scopes SET baseline_generation = 1;", Token, commit: true));
        foreach (var sql in new[]
                 {
                     "UPDATE connector_source_scopes SET enabled = false;",
                     "UPDATE connector_source_scopes SET baseline_generation = 0;",
                 })
        {
            var refused = await Assert.ThrowsAsync<PostgresException>(() => fresh.RuntimeAsync(tenant, sql, Token));
            Assert.True((PostgresErrorCodes.CheckViolation, "ck_connector_source_scopes_baseline") == (refused.SqlState, refused.ConstraintName), sql);
        }

        Assert.Equal(1L, await fresh.RuntimeAsync(tenant, "UPDATE connector_source_scopes SET enabled = false, baseline_generation = NULL;", Token, commit: true));
        var disabled = await Assert.ThrowsAsync<PostgresException>(() => fresh.RuntimeAsync(tenant, "UPDATE connector_source_scopes SET baseline_generation = 2;", Token));
        Assert.Equal((PostgresErrorCodes.CheckViolation, "ck_connector_source_scopes_baseline"), (disabled.SqlState, disabled.ConstraintName));

        // A field awaits a baseline at a real scope-set version, and its mark is the runtime role's to clear.
        var zero = await Assert.ThrowsAsync<PostgresException>(() => fresh.RuntimeAsync(tenant, "UPDATE reconciliation_targets SET awaiting_baseline_version = 0;", Token));
        Assert.Equal((PostgresErrorCodes.CheckViolation, "ck_reconciliation_targets_awaiting_baseline"), (zero.SqlState, zero.ConstraintName));
        Assert.Equal(1L, await fresh.RuntimeAsync(tenant, "UPDATE reconciliation_targets SET awaiting_baseline_version = 2;", Token, commit: true));
        Assert.Equal(1L, await fresh.RuntimeAsync(tenant, "UPDATE reconciliation_targets SET awaiting_baseline_version = NULL;", Token, commit: true));
    }

    [Fact]
    public async Task Another_tenant_sees_claims_and_changes_no_scope_or_sync_and_the_check_is_not_vacuous()
    {
        await using var fresh = await FreshDatabase.CreateAsync(fixture, "wce_it_gate3f_isolation", Token);
        await fresh.BootstrapAsync(Token);
        await fresh.MigrateAsync(Token);
        var (tenantA, connectionA) = await fresh.SeedConnectionAsync(Token);
        var (tenantB, _) = await fresh.SeedConnectionAsync(Token);
        await fresh.RuntimeAsync(tenantA, InsertScope(tenantA, connectionA, "9001"), Token, commit: true);
        await fresh.RuntimeAsync(tenantA, InsertSync(tenantA, connectionA), Token, commit: true);
        await fresh.RuntimeAsync(tenantA, InsertSyncScope(tenantA, connectionA, "9001"), Token, commit: true);

        foreach (var table in Tables)
        {
            var seen = $"SELECT count(*) FROM {table} WHERE tenant_id = '{tenantA.Value:D}';";
            Assert.Equal(1L, await fresh.RuntimeAsync(tenantA, seen, Token));
            Assert.Equal(0L, await fresh.RuntimeAsync(tenantB, seen, Token));
        }

        // Tenant B can neither claim A's generation nor enable A's scope, nor label a row with A's tenant.
        Assert.Equal(0L, await fresh.RuntimeAsync(tenantB, $"UPDATE connection_syncs SET claim_id = '{Guid.NewGuid():D}', claimed_until_utc = now() WHERE connection_id = '{connectionA:D}';", Token));
        Assert.Equal(0L, await fresh.RuntimeAsync(tenantB, $"UPDATE connector_source_scopes SET enabled = false WHERE connection_id = '{connectionA:D}';", Token));
        Assert.Equal(0L, await fresh.RuntimeAsync(tenantB, $"SELECT count(*) FROM (SELECT 1 FROM connection_syncs WHERE connection_id = '{connectionA:D}' FOR UPDATE) AS claimed;", Token));
        var labelled = await Assert.ThrowsAsync<PostgresException>(() => fresh.RuntimeAsync(tenantB, InsertScope(tenantA, connectionA, "9002"), Token));
        Assert.Equal(PostgresErrorCodes.InsufficientPrivilege, labelled.SqlState);

        // Tenant B cannot point its own scope at A's connection either: every key includes the tenant.
        var foreignKey = await Assert.ThrowsAsync<PostgresException>(() => fresh.RuntimeAsync(tenantB, InsertScope(tenantB, connectionA, "9003"), Token));
        Assert.Equal(PostgresErrorCodes.ForeignKeyViolation, foreignKey.SqlState);

        // Vacuity: without row-level security the same check sees the other tenant's rows, so it would have failed.
        foreach (var table in Tables)
        {
            await fresh.AdministrativeAsync($"ALTER TABLE {table} NO FORCE ROW LEVEL SECURITY; ALTER TABLE {table} DISABLE ROW LEVEL SECURITY;", Token);
            Assert.Equal(1L, await fresh.RuntimeAsync(tenantB, $"SELECT count(*) FROM {table} WHERE tenant_id = '{tenantA.Value:D}';", Token));
        }
    }

    private static string TablePrivileges(string table) =>
        $"""
        SELECT string_agg(p.privilege, ',' ORDER BY p.privilege)
        FROM (VALUES ('SELECT'), ('INSERT'), ('UPDATE'), ('DELETE'), ('TRUNCATE'), ('REFERENCES'), ('TRIGGER')) AS p(privilege)
        WHERE has_table_privilege('workcontinuity_app', 'public.{table}', p.privilege);
        """;

    private static string UpdateColumns(string table) =>
        $"""
        SELECT string_agg(a.attname, ',' ORDER BY a.attname)
        FROM pg_attribute a
        WHERE a.attrelid = 'public.{table}'::regclass AND a.attnum > 0 AND NOT a.attisdropped
          AND has_column_privilege('workcontinuity_app', a.attrelid, a.attnum, 'UPDATE');
        """;

    private static string InsertScope(TenantId tenant, Guid connection, string resource) =>
        $"""
        INSERT INTO connector_source_scopes (tenant_id, connection_id, source_system, resource_id, enabled, created_at_utc, updated_at_utc)
        VALUES ('{tenant.Value:D}', '{connection:D}', 'monday', '{resource}', true, now(), now());
        """;

    private static string InsertSync(TenantId tenant, Guid connection) =>
        $"""
        INSERT INTO connection_syncs (tenant_id, connection_id, source_system, generation, state, provider_subject, authorized_at_utc,
            scope_version, generation_scope_version, replay_floor, buffer_start_fence, attempts, started_at_utc, updated_at_utc)
        VALUES ('{tenant.Value:D}', '{connection:D}', 'monday', 1, 'Buffering', '58201774', now(), 1, 1, 0, 0, 0, now(), now());
        """;

    private static string InsertNotStarted(TenantId tenant, Guid connection) =>
        $"""
        INSERT INTO connection_syncs (tenant_id, connection_id, source_system, generation, state, scope_version, replay_floor,
            buffer_start_fence, attempts, updated_at_utc)
